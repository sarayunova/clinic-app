-- Ultrasound / Sonography Structured Reports
CREATE TABLE patient_ultrasound_reports (
  id                          INTEGER PRIMARY KEY,
  patient_id                  INTEGER NOT NULL REFERENCES patients(id),
  visit_id                    INTEGER REFERENCES visits(id),
  scan_date                   TEXT NOT NULL,
  scan_type                   TEXT NOT NULL CHECK (scan_type IN ('early_pregnancy', 'nt_first_trimester', 'anomaly_scan', 'growth_wellbeing', 'pelvic_gyn', 'other')),
  indication                  TEXT,
  clinical_lmp                TEXT,
  edd_by_lmp                  TEXT,
  edd_by_scan                 TEXT,
  gestational_age_weeks       INTEGER,
  gestational_age_days        INTEGER,
  fetal_number                TEXT DEFAULT 'single' CHECK (fetal_number IN ('single', 'twins', 'triplets', 'none')),
  cardiac_activity            TEXT DEFAULT 'present' CHECK (cardiac_activity IN ('present', 'absent', 'not_applicable')),
  fhr_bpm                     INTEGER,
  presentation                TEXT CHECK (presentation IS NULL OR presentation IN ('cephalic', 'breech', 'transverse', 'oblique', 'variable', 'not_applicable')),
  placenta_location           TEXT CHECK (placenta_location IS NULL OR placenta_location IN ('anterior', 'posterior', 'fundal', 'low_lying', 'previa', 'not_applicable')),
  placenta_grade              TEXT CHECK (placenta_grade IS NULL OR placenta_grade IN ('0', '1', '2', '3', 'not_applicable')),
  amniotic_fluid_type         TEXT CHECK (amniotic_fluid_type IS NULL OR amniotic_fluid_type IN ('afi', 'sdp', 'adequate', 'reduced', 'increased', 'not_applicable')),
  amniotic_fluid_cm           REAL,
  amniotic_fluid_assessment   TEXT CHECK (amniotic_fluid_assessment IS NULL OR amniotic_fluid_assessment IN ('normal', 'borderline', 'oligohydramnios', 'polyhydramnios', 'not_applicable')),
  gsd_mm                      REAL,
  crl_mm                      REAL,
  nt_mm                       REAL,
  nasal_bone                  TEXT CHECK (nasal_bone IS NULL OR nasal_bone IN ('present', 'absent', 'hypoplastic', 'not_visualized')),
  bpd_mm                      REAL,
  hc_mm                       REAL,
  ac_mm                       REAL,
  fl_mm                       REAL,
  efw_grams                   INTEGER,
  efw_percentile              TEXT,
  anatomy_survey              TEXT,
  uterus_findings             TEXT,
  endometrial_thickness_mm    REAL,
  right_ovary_findings        TEXT,
  left_ovary_findings         TEXT,
  free_fluid                  TEXT CHECK (free_fluid IS NULL OR free_fluid IN ('none', 'minimal', 'moderate', 'gross')),
  impression                  TEXT NOT NULL,
  recommendations             TEXT,
  sonographer_name            TEXT,
  attachment_id               INTEGER REFERENCES attachments(id),
  created_by                  INTEGER NOT NULL REFERENCES users(id),
  updated_by                  INTEGER NOT NULL REFERENCES users(id),
  created_at                  TEXT NOT NULL,
  updated_at                  TEXT NOT NULL
);

CREATE INDEX idx_ultrasound_reports_patient ON patient_ultrasound_reports(patient_id);
CREATE INDEX idx_ultrasound_reports_date ON patient_ultrasound_reports(scan_date);
